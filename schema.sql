-- Sistema de telas remotas
create table if not exists public.screens (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  name text not null,
  html text not null,
  is_global boolean not null default false,
  is_active boolean not null default true
);

create table if not exists public.devices (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  device_id text not null unique,
  screen_id bigint references public.screens(id),
  screen_active boolean not null default true,
  label text,
  last_seen timestamptz
);

-- RLS: acesso público de leitura via API (service_role ignora)
alter table public.screens enable row level security;
alter table public.devices enable row level security;

drop policy if exists "leitura publica screens" on public.screens;
create policy "leitura publica screens" on public.screens for select to anon using (true);
drop policy if exists "leitura publica devices" on public.devices for select to anon using (true);
create policy "leitura publica devices" on public.devices for select to anon using (true);
drop policy if exists "escrita publica devices" on public.devices for insert to anon with check (true);
create policy "escrita publica devices" on public.devices for insert to anon with check (true);
drop policy if exists "update publico devices" on public.devices for update to anon using (true) with check (true);
create policy "update publico devices" on public.devices for update to anon using (true) with check (true);

